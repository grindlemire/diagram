// siEntry is one icon's entry in Simple Icons' data file.
type siEntry struct {
	Title      string `json:"title"`
	Slug       string `json:"slug"`
	Hex        string `json:"hex"`
	Source     string `json:"source"`
	Guidelines string `json:"guidelines,omitempty"`
	License    *struct {
		Type string `json:"type"`
		URL  string `json:"url,omitempty"`
	} `json:"license,omitempty"`
}

// licenceOf returns an icon's SPDX licence, or "" when it is covered by
// Simple Icons' own CC0 dedication.
func (e siEntry) licenceOf() string {
	if e.License == nil || e.License.Type == "CC0-1.0" {
		return ""
	}
	return e.License.Type
}

var (
	hexRe  = regexp.MustCompile(`^[0-9A-Fa-f]{6}$`)
	spdxRe = regexp.MustCompile(`^[A-Za-z0-9.+-]+$`)
)

// generate returns the files of one package: icons.go and its licence files.
func generate(s set, sources string) (map[string][]byte, error) {
	dir := filepath.Join(sources, s.Source)
	version, err := readVersion(dir)
	if err != nil {
		return nil, err
	}
	icons := slices.Clone(s.Icons)
	slices.SortFunc(icons, func(a, b icon) int { return strings.Compare(a.Name, b.Name) })
	if err := checkNames(icons); err != nil {
		return nil, err
	}
	if !slices.ContainsFunc(icons, func(ic icon) bool { return ic.Name == s.Example }) {
		return nil, fmt.Errorf("example %q is not in the set", s.Example)
	}

	files := map[string][]byte{}
	var data map[string]siEntry
	switch s.Source {
	case "lucide":
		if files["LICENSE"], err = os.ReadFile(filepath.Join(dir, "LICENSE")); err != nil {
			return nil, err
		}
	case "simple-icons":
		if files["LICENSE.md"], err = os.ReadFile(filepath.Join(dir, "LICENSE.md")); err != nil {
			return nil, err
		}
		if data, err = readSimpleIconsData(dir); err != nil {
			return nil, err
		}
	default:
		return nil, fmt.Errorf("unknown source %q", s.Source)
	}

	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by cmd/gen-icons; DO NOT EDIT.\n\n")
	writePackageDoc(&b, s, version)
	p("package %s\n\nimport \"github.com/grindlemire/diagram/icons\"\n\n", s.Pkg)

	if s.Source == "simple-icons" {
		p("// Entry is one icon in the set.\ntype Entry struct {\n")
		p("\tName  string // exported variable name, such as %q\n", s.Example)
		p("\tIcon  *icons.Icon\n")
		p("\tColor string // the brand's colour as #RRGGBB, from Simple Icons\n}\n\n")
	} else {
		p("// Entry is one icon in the set.\ntype Entry struct {\n")
		p("\tName string // exported variable name, such as %q\n", s.Example)
		p("\tIcon *icons.Icon\n}\n\n")
	}

	p("var (\n")
	for i, ic := range icons {
		src, err := os.ReadFile(filepath.Join(dir, "icons", ic.Slug+".svg"))
		if err != nil {
			return nil, err
		}
		opts := lucideOpts
		if s.Source == "simple-icons" {
			opts = simpleIconsOpts
		}
		svg, err := minify(src, opts)
		if err != nil {
			return nil, fmt.Errorf("%s.svg: %w", ic.Slug, err)
		}
		if i > 0 {
			p("\n")
		}
		switch s.Source {
		case "lucide":
			p("\t// %s is Lucide's %q icon.\n", ic.Name, ic.Slug)
		case "simple-icons":
			e, ok := data[ic.Slug]
			if !ok {
				return nil, fmt.Errorf("%s: no entry in data.json", ic.Slug)
			}
			p("\t// %s is the %s logo (Simple Icons %q).\n\t// Its brand colour is %sColor.", ic.Name, e.Title, ic.Slug, ic.Name)
			if l := e.licenceOf(); l != "" {
				name := "LICENSE-" + l + ".txt"
				text, err := os.ReadFile(filepath.Join(dir, "licenses", l+".txt"))
				if err != nil {
					return nil, fmt.Errorf("%s is %s licensed and needs its text vendored: %w", ic.Slug, l, err)
				}
				files[name] = text
				p("\n\t// This icon is licensed under %s; see %s.", l, name)
			}
			p("\n")
		}
		p("\t%s = icons.MustSVG(%q, %s)\n", ic.Name, ic.Slug, goString(svg))
	}
	p(")\n\n")

	if s.Source == "simple-icons" {
		p("// Brand colours, as published by Simple Icons. Pass one to themes.Hex to\n")
		p("// draw an icon in its brand colour.\nconst (\n")
		for _, ic := range icons {
			p("\t%sColor = %q\n", ic.Name, "#"+strings.ToUpper(data[ic.Slug].Hex))
		}
		p(")\n\n")
	}

	p("// All returns every icon in the set, sorted by name.\nfunc All() []Entry {\n\treturn []Entry{\n")
	for _, ic := range icons {
		if s.Source == "simple-icons" {
			p("\t\t{%q, %s, %sColor},\n", ic.Name, ic.Name, ic.Name)
		} else {
			p("\t\t{%q, %s},\n", ic.Name, ic.Name)
		}
	}
	p("\t}\n}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, b.Bytes())
	}
	files["icons.go"] = src
	return files, nil
}

func writePackageDoc(b *bytes.Buffer, s set, version string) {
	var doc string
	switch s.Source {
	case "lucide":
		doc = fmt.Sprintf(`Package %s %s

The icons are from Lucide v%s (https://lucide.dev), licensed under the
ISC licence; icons Lucide derived from Feather are also under the MIT
licence. Both notices are in the LICENSE file in this directory, which must
accompany copies of these icons.

The icons are stroked with currentColor, so a diagram draws them in its
icon colour.`, s.Pkg, s.Blurb, version)
	case "simple-icons":
		doc = fmt.Sprintf(`Package %s %s

The icons are from Simple Icons v%s (https://simpleicons.org), dedicated to
the public domain under CC0 1.0 (see LICENSE.md) unless an icon's comment
names another licence, whose text is in this directory. The logos are
trademarks of their owners, and using them may be subject to the owners'
brand guidelines.

The icons are filled with currentColor, so a diagram draws them in its icon
colour. Each icon has a sibling constant with its brand colour, such as
%sColor.`, s.Pkg, s.Blurb, version, s.Example)
	}
	for i, para := range strings.Split(doc, "\n\n") {
		if i > 0 {
			b.WriteString("//\n")
		}
		line := "//"
		for _, w := range strings.Fields(para) {
			if len(line)+1+len(w) > 77 && line != "//" {
				b.WriteString(line + "\n")
				line = "//"
			}
			line += " " + w
		}
		b.WriteString(line + "\n")
	}
}

// goString returns s as a Go string literal, raw where possible.
func goString(s string) string {
	if !strings.Contains(s, "`") && !strings.Contains(s, "\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

func checkNames(icons []icon) error {
	seen := map[string]bool{}
	for _, ic := range icons {
		if !token.IsIdentifier(ic.Name) || !token.IsExported(ic.Name) {
			return fmt.Errorf("%q is not an exported Go identifier", ic.Name)
		}
		if ic.Name == "All" || ic.Name == "Entry" || strings.HasSuffix(ic.Name, "Color") {
			return fmt.Errorf("name %q collides with generated declarations", ic.Name)
		}
		if seen[ic.Name] {
			return fmt.Errorf("duplicate name %q", ic.Name)
		}
		seen[ic.Name] = true
	}
	return nil
}

func readVersion(dir string) (string, error) {
	v, err := os.ReadFile(filepath.Join(dir, "VERSION"))
	if err != nil {
		return "", err
	}
	s := strings.TrimSpace(string(v))
	if s == "" {
		return "", errors.New(dir + "/VERSION is empty")
	}
	return s, nil
}

func readSimpleIconsData(dir string) (map[string]siEntry, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "data.json"))
	if err != nil {
		return nil, err
	}
	var entries []siEntry
	if err := json.Unmarshal(raw, &entries); err != nil {
		return nil, fmt.Errorf("data.json: %w", err)
	}
	m := make(map[string]siEntry, len(entries))
	for _, e := range entries {
		if !hexRe.MatchString(e.Hex) {
			return nil, fmt.Errorf("data.json: %s has bad hex %q", e.Slug, e.Hex)
		}
		if l := e.licenceOf(); l != "" && !spdxRe.MatchString(l) {
			return nil, fmt.Errorf("data.json: %s has bad licence %q", e.Slug, l)
		}
		m[e.Slug] = e
	}
	return m, nil
}
